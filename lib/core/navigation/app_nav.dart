import 'package:get/get.dart';

/// جایگزینِ `Get.back()`.
///
/// 🔧 رفعِ باگ (دو بار تکمیل شدنِ کار / دو کارِ تکراری): در GetX 4.x اگر
/// اسنک‌باری باز باشد، `Get.back()` فقط همان اسنک‌بار را می‌بندد و دیالوگ
/// یا صفحه سرِ جایش می‌ماند — کاربر فکر می‌کند «اتفاقی نیفتاد» و دوباره
/// می‌زند، در حالی که عملیاتِ بعد از `Get.back()` همان بارِ اول اجرا شده
/// بود. این تابع همیشه بالاترین مسیر (دیالوگ/شیت/صفحه) را می‌بندد و به
/// اسنک‌بارِ باز کاری ندارد.
class AppNav {
  AppNav._();

  static void back<T>({T? result}) {
    final nav = Get.key.currentState;
    if (nav != null && nav.canPop()) nav.pop<T>(result);
  }
}
