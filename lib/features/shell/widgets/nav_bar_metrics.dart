import 'package:flutter/widgets.dart';

/// فاصله‌ای که محتوایِ هر تب (داشبورد/کارها/اعلان‌ها/تنظیمات) باید از
/// پایین رزرو کند تا آخرین آیتمِ لیست پشتِ نوارِ پایین گم نشود.
///
/// ⚠️ باید هم‌راستا با اندازه‌های واقعیِ نوار در main_shell.dart بماند:
/// نوار به بالای دکمه‌های گوشی چسبیده، پس فوتپرینتِ کلش «ارتفاعِ خودِ کارت
/// (۲۸) + inset سیستم» است، به‌علاوه‌ی یک فاصله‌ی نفسِ کوچک (۲۰) تا آخرین
/// آیتم درست بالای نوار بنشیند، نه چسبیده به آن.
double bottomNavClearance(BuildContext context) {
  return 52 + MediaQuery.of(context).padding.bottom;
}
